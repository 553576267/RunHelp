use rusqlite::Connection;

use crate::state::AppState;

/// 从数据库读取当前界面语言；缺失或异常时回退简体中文。
pub fn lang_from_conn(conn: &Connection) -> String {
    conn.query_row(
        "SELECT value FROM settings WHERE key='language'",
        [],
        |r| r.get::<_, String>(0),
    )
    .unwrap_or_else(|_| "zh-CN".to_string())
}

/// 便捷入口：从 AppState 取语言。
pub fn lang(state: &AppState) -> String {
    state
        .conn()
        .map(|conn| lang_from_conn(&conn))
        .unwrap_or_else(|_| "zh-CN".to_string())
}

/// key 使用中文原文：中文环境原样返回，英文环境查 EN 表，缺条目时仍返回原文。
pub fn tr(language: &str, key: &str) -> String {
    if language != "en-US" {
        return key.to_string();
    }
    EN.iter()
        .find(|(k, _)| *k == key)
        .map(|(_, v)| (*v).to_string())
        .unwrap_or_else(|| key.to_string())
}

/// 带 {name} 占位的版本。
pub fn trf(language: &str, key: &str, vars: &[(&str, &str)]) -> String {
    let mut text = tr(language, key);
    for (name, value) in vars {
        text = text.replace(&format!("{{{}}}", name), value);
    }
    text
}

